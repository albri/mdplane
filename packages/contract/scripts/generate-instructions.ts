// Builds the instructions an agent gets from `GET /{tier}/{key}` out of the OpenAPI spec and
// src/instructions.md, so they always list exactly the requests the link is allowed to make. Also
// builds the start instructions at `GET /` from src/start.md, with its requests from the spec.
import { readFileSync, writeFileSync } from 'node:fs'
import { parse } from 'yaml'

type Schema = { $ref?: string; enum?: string[] }
type Parameter = { $ref?: string; name?: string; in?: string; schema?: Schema }
type Operation = { operationId: string; summary: string; parameters?: Parameter[] }
type PathItem = { parameters?: Parameter[] } & Partial<Record<Method, Operation>>
type Method = (typeof METHODS)[number]

const METHODS = ['get', 'put', 'post', 'delete'] as const
const TIERS = ['r', 'a', 'w'] as const
type Tier = (typeof TIERS)[number]

const root = new URL('..', import.meta.url)
// oxlint-disable-next-line typescript/no-unsafe-type-assertion -- our own spec; `redocly lint` validates it
const spec = parse(readFileSync(new URL('openapi.yaml', root), 'utf8')) as {
  paths: Record<string, PathItem>
  components: { parameters: Record<string, Parameter>; schemas: Record<string, Schema> }
}
const template = readFileSync(new URL('src/instructions.md', root), 'utf8')
const startTemplate = readFileSync(new URL('src/start.md', root), 'utf8')

function lookup<T>(ref: string, prefix: string, table: Record<string, T>): T {
  const found = table[ref.replace(prefix, '')]
  if (!found) throw new Error(`Unknown reference ${ref}`)
  return found
}

function resolve(param: Parameter): Parameter {
  const resolved = param.$ref
    ? lookup(param.$ref, '#/components/parameters/', spec.components.parameters)
    : param
  const schema = resolved.schema?.$ref
    ? lookup(resolved.schema.$ref, '#/components/schemas/', spec.components.schemas)
    : resolved.schema
  return { ...resolved, ...(schema && { schema }) }
}

// Operation parameters override path parameters with the same name and location.
function parametersOf(item: PathItem, op: Operation): Parameter[] {
  const merged = new Map<string, Parameter>()
  for (const param of [...(item.parameters ?? []), ...(op.parameters ?? [])].map(resolve)) {
    merged.set(`${param.in}:${param.name}`, param)
  }
  return [...merged.values()]
}

const KEYED = '/{tier}/{key}'

// One request as a list item. `link` stands in for the link in keyed paths, and `origin` for the
// server elsewhere.
function requestLine(path: string, method: Method, op: Operation, link: string, origin = '') {
  const query = parametersOf(spec.paths[path] ?? {}, op)
    .filter((p) => p.in === 'query')
    .map((p) => `${p.name}={${p.name}}`)
  const base = path.startsWith(KEYED) ? `${link}${path.slice(KEYED.length)}` : `${origin}${path}`
  const url = `${base}${query.length ? `?${query.join('&')}` : ''}`
  return `- \`${method.toUpperCase()} ${url}\`: ${op.summary}.`
}

function operationLines(tier: Tier): string {
  const lines: string[] = []
  for (const [path, item] of Object.entries(spec.paths)) {
    if (!path.startsWith(KEYED)) continue
    for (const method of METHODS) {
      const op = item[method]
      if (!op) continue
      const params = parametersOf(item, op)
      const tiers = params.find((p) => p.in === 'path' && p.name === 'tier')?.schema?.enum
      if (!tiers) throw new Error(`${op.operationId} has no tier enum`)
      if (!tiers.includes(tier)) continue
      lines.push(requestLine(path, method, op, '$URL'))
    }
  }
  return lines.join('\n')
}

// The requests named in `{{requests: id id …}}`, in that order. The origin stays a placeholder
// that the Worker fills in, so the instructions name the server they came from.
function namedLines(ids: string[]): string {
  return ids
    .map((id) => {
      for (const [path, item] of Object.entries(spec.paths)) {
        for (const method of METHODS) {
          if (item[method]?.operationId === id) {
            return requestLine(path, method, item[method], '$WRITE', '{{origin}}')
          }
        }
      }
      throw new Error(`Unknown operation ${id}`)
    })
    .join('\n')
}

// Keeps `<!-- tier: … -->` blocks that name the tier and drops the rest.
function render(tier: Tier): string {
  const body = template.replace(
    /<!-- tier: ([a-z ]+) -->\n([\s\S]*?)<!-- end -->\n/g,
    (_, tiers: string, block: string) => (tiers.split(' ').includes(tier) ? block : ''),
  )
  return body.replace('{{operations}}', operationLines(tier))
}

const start = startTemplate.replace(/\{\{requests: ([A-Za-z ]+)\}\}/, (_, ids: string) =>
  namedLines(ids.split(' ')),
)

const entries = TIERS.map((tier) => `  ${tier}: ${JSON.stringify(render(tier))},`).join('\n')
writeFileSync(
  new URL('src/generated/instructions.gen.ts', root),
  `// Generated by scripts/generate-instructions.ts from openapi.yaml, src/instructions.md and src/start.md.\n\nexport const instructions = {\n${entries}\n} as const\n\nexport const start = ${JSON.stringify(start)}\n`,
)
